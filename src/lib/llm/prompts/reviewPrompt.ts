export function buildUserPrompt(input: DraftInput): string {
  const parts: string[] = [];

  if (input.place) {
    parts.push(`방문 장소: ${input.place.name}`);
    const addr = (input.place as { roadAddress?: string }).roadAddress ?? input.place.address;
    if (addr) parts.push(`주소: ${addr}`);
    if (input.place.category) parts.push(`카테고리: ${input.place.category}`);
  } else {
    parts.push("방문 장소 정보는 따로 없습니다. 사진과 메모로 글을 구성해주세요.");
  }

  if (input.mood) {
    parts.push(`\n방문 인상 (사용자 메모):\n"${input.mood}"`);
  }

  if (input.keywords.length) {
    parts.push(
      `\n사용자가 강조한 키워드 (본문에 2~3회 자연 등장, frontmatter \`tags\` 에도 우선 포함):\n${input.keywords.map((k) => `- ${k}`).join("\n")}`,
    );
  }

  parts.push(
    `\n첨부된 사진은 ${input.photos.length}장이며, 1번부터 ${input.photos.length}번까지 사용자가 올린 순서입니다.`,
  );
  parts.push(
    `각 사진을 본문에서 \`[이미지 1]\`부터 \`[이미지 ${input.photos.length}]\`까지 **한 번씩만** 자리표시자로 끼워넣어주세요. 첫 사진은 도입부 직후 또는 첫 본문 단락 직전에, 나머지는 흐름상 자연스러운 위치에 배치합니다.`,
  );
  parts.push(
    `\n위 정보와 시스템 지침(페르소나·톤·구조·SEO·어뷰징 회피)을 모두 반영하여 작성해주세요. 매번 다른 도입부와 소제목 표현을 사용하세요.`,
  );

  return parts.join("\n");
}
